import fs from 'node:fs';
import assert from 'node:assert/strict';
const pages=fs.readFileSync('functions/realtime.js','utf8');
const worker=fs.readFileSync('realtime-worker/realtime.js','utf8');
const ui=fs.readFileSync('public/script.js','utf8');
const api=fs.readFileSync('functions/myCloudinaryHandler.js','utf8');
assert.match(pages,/auth_sessions s JOIN auth_users u ON u\.username_key=lower\(s\.username\)/,'realtime must use authoritative enabled account role/scope');
assert.match(pages,/COALESCE\(u\.enabled,0\)=1/,'disabled accounts must not connect');
assert.match(pages,/SELECT id,opd FROM opd_data WHERE year=\?/,'OPD names must be resolved to year-specific stable IDs');
assert.match(pages,/X-Kawal-Realtime-Access/,'trusted Pages proxy must pass access tier to the DO');
assert.match(pages,/X-Kawal-Realtime-Opd-Ids/,'trusted Pages proxy must pass authorized OPD IDs to the DO');
assert.match(pages,/forwardHeaders\.delete\('cookie'\)/,'session cookies must not be forwarded into the DO');
assert.match(worker,/ws\.deserializeAttachment\(\)/,'DO must enforce per-connection scope');
assert.match(worker,/scope\.allowedOpdIds\.includes\(eventOpdId\)/,'scoped connections receive only their OPD events');
assert.match(worker,/if \(scope\.year && scope\.year !== eventYear\) continue/,'events must not cross years');
assert.match(worker,/server\.serializeAttachment\(\{ year, access, role, allowedOpdIds/,'socket scope must be bound at authenticated connection time');
assert.doesNotMatch(ui,/currentUser\?\.role === 'opd' \|\| currentUser\?\.scoped\).*Realtime lintas OPD nonaktif/,'client must not disable realtime for all scoped accounts');
assert.match(ui,/connectRealtime\(\)/,'client must connect authenticated, scoped sessions');
assert.match(api,/INSERT INTO auth_sessions\(token_hash,username/,'each operator device receives its own hashed session row');
assert.match(api,/WHERE token_hash=\?/,'logout revokes only the current device session');
console.log(JSON.stringify({status:'PASS',checks:14,verified:['authoritative identity','per-year OPD scope resolution','message-level filtering','no cookie forwarding','multiple hashed sessions per account']},null,2));
